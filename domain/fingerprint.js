const rotr = (value, bits) => (value >>> bits) | (value << (32 - bits));

// SHA-256 of a text or of bytes, as 64 lowercase hex characters. Written out here because the
// browser's own digest call is asynchronous and the services are not.
export function sha256Hex(content) {
  const data = content instanceof Uint8Array ? content : new TextEncoder().encode(String(content));
  const padded = new Uint8Array(((data.length + 9 + 63) >> 6) << 6);
  padded.set(data);
  padded[data.length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor((data.length * 8) / 0x100000000));
  view.setUint32(padded.length - 4, (data.length * 8) >>> 0);
  const state = Uint32Array.from([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  const w = new Uint32Array(64);
  for (let block = 0; block < padded.length; block += 64) {
    for (let i = 0; i < 16; i += 1) w[i] = view.getUint32(block + i * 4);
    for (let i = 16; i < 64; i += 1) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }
    let [a, b, c, d, e, f, g, h] = state;
    for (let i = 0; i < 64; i += 1) {
      const sum1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const choose = (e & f) ^ (~e & g);
      const t1 = (h + sum1 + choose + K[i] + w[i]) >>> 0;
      const sum0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const majority = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (sum0 + majority) >>> 0;
      h = g;
      g = f;
      f = e;
      e = (d + t1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) >>> 0;
    }
    const next = [a, b, c, d, e, f, g, h];
    for (let i = 0; i < 8; i += 1) state[i] = (state[i] + next[i]) >>> 0;
  }
  return [...state].map((word) => word.toString(16).padStart(8, "0")).join("");
}

// A short, readable fingerprint of a content: the first 16 characters of its SHA-256.
export const fingerprint = (content) => sha256Hex(content).slice(0, 16);

// The simulated signature of a webhook delivery: a fingerprint of the endpoint key and the exact
// body. It stands in for the real system's HMAC and is NOT cryptographic: the key is stored in the
// browser, so anyone with the page can compute it. It only shows the check and its outcomes.
export const SIGNATURE_PREFIX = "sim-";
export const simulatedSignature = (endpointKey, body) =>
  `${SIGNATURE_PREFIX}${fingerprint(`${endpointKey}\n${body}`)}`;

export function signatureMatches(endpointKey, body, signature) {
  return typeof signature === "string" && signature === simulatedSignature(endpointKey, body);
}
